import { uid, slugify } from '../lib/utils'

const sleep = (ms) => new Promise((resolve) => setTimeout(resolve, ms))

let documents = []

export async function listDocuments() {
  await sleep(250)
  return documents.map((d) => ({ ...d }))
}

export async function uploadDocument(file, onProgress) {
  for (let p = 0; p <= 100; p += 25) {
    onProgress?.(p)
    await sleep(150)
  }
  const doc = {
    id: uid(),
    name: file.name,
    size: file.size,
    status: 'ready', // 'processing' | 'ready' | 'error'
    chunks: Math.max(4, Math.round(file.size / 2500)),
  }
  documents = [doc, ...documents]
  return doc
}

export async function deleteDocument(id) {
  await sleep(150)
  documents = documents.filter((d) => d.id !== id)
}

export async function sendMessage({ message, documentIds = [], sources }) {
  await sleep(1600)

  const candidates = []

  if (sources.documents && documentIds.length) {
    const doc = documents.find((d) => d.id === documentIds[0])
    candidates.push({
      id: uid(),
      source_type: 'document',
      title: doc ? doc.name : 'Uploaded document',
      url: null,
      authors: null,
      year: null,
      snippet:
        'Passage retrieved from your uploaded file. In the real system this is the chunk with the highest semantic similarity to the question.',
      relevance: 0.94,
      credibility: 0.7,
    })
  }
  if (sources.academic) {
    candidates.push(
      {
        id: uid(),
        source_type: 'academic',
        title: 'Sample academic paper A (mock data)',
        url: 'https://example.org/paper-a',
        authors: 'A. Author, B. Author',
        year: 2023,
        snippet:
          'This is placeholder text standing in for an abstract returned by an academic database.',
        relevance: 0.88,
        credibility: 0.95,
      },
      {
        id: uid(),
        source_type: 'academic',
        title: 'Sample academic paper B (mock data)',
        url: 'https://example.org/paper-b',
        authors: 'C. Author',
        year: 2021,
        snippet: 'Another placeholder abstract used to demonstrate ranking and citation display.',
        relevance: 0.74,
        credibility: 0.9,
      },
    )
  }
  if (sources.web) {
    candidates.push({
      id: uid(),
      source_type: 'web',
      title: 'Sample web article (mock data)',
      url: 'https://example.org/article',
      authors: null,
      year: 2025,
      snippet: 'Placeholder snippet from a live web search result.',
      relevance: 0.81,
      credibility: 0.55,
    })
  }

  // Backend thật xếp hạng theo relevance + credibility; mock mô phỏng lại
  const score = (e) => e.relevance * 0.6 + e.credibility * 0.4
  const evidence = candidates.sort((a, b) => score(b) - score(a))

  if (evidence.length === 0) {
    return {
      message_id: uid(),
      answer:
        'No knowledge source is enabled. Turn on at least one source (documents, web or academic) below the message box and ask again.',
      evidence: [],
    }
  }

  const cite = (i) => (evidence[i] ? ` [${i + 1}]` : '')

  const answer = [
    '## Overview',
    `This is a **mock answer** to: *"${message}"*. The real answer will be generated by the LLM from the ranked evidence on the right.${cite(0)}`,
    '## Key findings',
    `- Finding one is supported by the highest-ranked source.${cite(0)}`,
    `- Finding two is backed by an independent source, which increases confidence.${cite(1)}`,
    `- Finding three comes from a lower-ranked source and should be verified.${cite(2)}`,
    '## Comparison',
    '| Aspect | Observation |',
    '| --- | --- |',
    '| Evidence quality | Higher for academic sources |',
    '| Recency | Higher for web sources |',
    '## Next steps',
    '1. Open each cited source in the Evidence panel.',
    '2. Verify claims that rely on a single source.',
  ].join('\n\n')

  return { message_id: uid(), answer, evidence }
}

export async function exportAnswer({ format, title, content }) {
  await sleep(500)
  // Mock chỉ xuất Markdown; backend thật sẽ trả về file .pdf / .docx
  const blob = new Blob([`# ${title}\n\n${content}`], { type: 'text/markdown' })
  return { blob, filename: `${slugify(title)}-mock-${format}.md` }
}
