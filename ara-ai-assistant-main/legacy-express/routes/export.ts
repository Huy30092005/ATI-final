import { Router, Request, Response } from 'express';
import { formatBibliography } from '../../src/utils/scoring.ts';

export const exportRouter = Router();

exportRouter.post('/', (req: Request, res: Response) => {
  const { format, data } = req.body;
  if (!data) return res.status(400).json({ error: 'Missing data payload' });

  const bib = formatBibliography(data.ranked_evidence || []);

  if (format === 'bibtex') {
    return res.type('text/plain').send(bib.bibtex);
  }

  if (format === 'html') {
    const html = `<!DOCTYPE html>
<html>
<head>
<meta charset="utf-8">
<title>ARA Research Brief - ${data.query}</title>
<style>
body { font-family: system-ui, -apple-system, sans-serif; line-height: 1.6; max-width: 820px; margin: 40px auto; padding: 24px; color: #0f172a; }
h1, h2, h3 { color: #0f172a; }
.badge { display: inline-block; background: #e0e7ff; color: #3730a3; padding: 2px 8px; border-radius: 9999px; font-size: 12px; font-weight: 600; }
pre { white-space: pre-wrap; font-family: inherit; }
</style>
</head>
<body>
<h1>ARA Research Brief: ${data.query}</h1>
<p><span class="badge">Generated by ARA</span> &bull; <em>${new Date().toLocaleDateString()}</em></p>
<hr/>
<pre>${data.synthesized_answer}</pre>
<h2>References</h2>
<ol>
${bib.apa.map(a => `<li>${a}</li>`).join('')}
</ol>
</body>
</html>`;
    return res.type('text/html').send(html);
  }

  // Default Markdown
  const md = `# ARA Research Brief: ${data.query}
*Generated by ARA (AI Research Assistant)*

${data.synthesized_answer}

## References
${bib.apa.join('\n\n')}`;

  res.type('text/markdown').send(md);
});
